mark('n23', 'ЧАСТИЧНО', '1.1–1.3: ночная смена и замки показывают работу охранника. Жильё при клубе не показано и не названо.');
mark('n24 n28', 'ЧАСТИЧНО', 'Рутина, пустота и состояние — 1–3, 6.3. Бедность как конкретный факт не установлена.');
mark('n29', 'ЧАСТИЧНО', 'Ночная одиночная игра есть (3–5). Коморка и начало дня в ней отсутствуют в v16.');
mark('n27', 'ЧАСТИЧНО', '4.1 сообщает о прежней цели и борьбе; адреналин и характер отношения к риску не раскрыты.');
mark('n40 n41', 'ЧАСТИЧНО', 'Есть рассказ о выборе проиграть бой; он сам по себе не доказывает упорство или устойчивое отношение к риску.');
mark('n73', 'ЧАСТИЧНО', '6.3: опущенная голова и неподвижность дают ощущение поражения; физическая усталость не установлена отдельно.');
mark('n74 n76', 'ЧАСТИЧНО', 'На экране бильярд, в голосе бокс. Ставка, соперник и давление бильярдного турнира появятся позже.');
mark('n77 n78 n150 n155', 'ЧАСТИЧНО', 'Удары и промах присутствуют; сюжетная цепь последствий ещё не разыграна. Метафора требует дальнейших сцен.');
