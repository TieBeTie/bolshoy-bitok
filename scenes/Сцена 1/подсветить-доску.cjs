const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const board = JSON.parse(fs.readFileSync(path.join(root, 'Доска.canvas'), 'utf8'));
const evidence = {};
function mark(ids, state, proof) {
  for (const id of ids.split(' ')) evidence[id] = { state, proof };
}
mark('n26 n64 n69', 'КАДР', '3.1–3.5: стол, включение верхнего света, бутылка, халат, одиночная игра.');
mark('n25', 'ГОЛОС', '4.1: раньше был гонг, соперник и понятная цель; нынешняя бесцельность — 3.2–3.5.');
mark('n42 n44 n48', 'ГОЛОС', '4.2–5.3: намеренно проигранный бой, предательство организатора, лишение лицензии. Его нынешняя личность ещё не раскрыта.');
mark('n43', 'ГОЛОС', '4.1: гонг и соперник давали направление жизни.');
mark('n66', 'ЧАСТИЧНО', '3.2, 5.2, 6.3: верхний и контрастный свет; отражения как отдельный приём не подтверждены.');
mark('n67', 'ЧАСТИЧНО', '1.3 и 3.3: крупно руки и детали. Денег в первой сцене нет.');
